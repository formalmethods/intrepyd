from helper import from_fixture_path
from os.path import join
from intrepyd.lustre2py import translator
from intrepyd.engine import EngineResult
import intrepyd.context
import os
import sys
import importlib
import multiprocessing as mp
import time

PATH_TO_KIND2_BENCHMARKS_ROOT = from_fixture_path('kind2-benchmarks/')

def _load_encoding():
    """
    Imports the encoding module generated by the translator.

    The cwd is added to sys.path explicitly: since python 3.14 the default
    multiprocessing start method on linux is forkserver, and the worker process
    no longer inherits the parent's sys.path, so a plain import of a module
    written into the current directory would fail.
    """
    sys.path.insert(0, os.getcwd())
    importlib.invalidate_caches()
    return importlib.import_module('encoding')

def worker_br(q):
    """
    Executes a translated benchmark
    """
    start = time.time()
    try:
        enc = _load_encoding()
        ctx = intrepyd.context.Context()
        circ = enc.mk_instance(ctx, 'br')
        circ.mk_circuit()
        breach = ctx.mk_backward_reach()
        breach.add_target(ctx.mk_not(circ.outputs['OK']))
        eng_result = breach.reach_targets()
        result = 'Unknown'
        if eng_result == EngineResult.REACHABLE:
            result = 'Invalid'
        elif eng_result == EngineResult.UNREACHABLE:
            result = 'Valid'
    except Exception as exc:  # pylint: disable=broad-except
        result = 'Exception ' + str(exc)
    q.put([result, time.time() - start])

def worker_bmc(q):
    """
    Executes a translated benchmark
    """
    start = time.time()
    result = 'Unknown'
    try:
        enc = _load_encoding()
        ctx = intrepyd.context.Context()
        circ = enc.mk_instance(ctx, 'bmc')
        circ.mk_circuit()
        bmc = ctx.mk_bmc()
        bmc.add_target(ctx.mk_not(circ.outputs['OK']))
        for depth in range(100000):
            bmc.set_current_depth(depth)
            eng_result = bmc.reach_targets()
            if eng_result == EngineResult.REACHABLE:
                result = 'Invalid'
                break
    except Exception as exc:  # pylint: disable=broad-except
        result = 'Exception ' + str(exc)
    q.put([result, time.time() - start])

